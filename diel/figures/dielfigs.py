"""Figure generation for the diel-activity analysis.

EVERY figure in the paper and the report is generated by a function in this module. Nothing is
drawn ad hoc in a session. If a figure needs changing, change it here, rerun, and commit: the next
iteration then starts from working code instead of rebuilding from the data.

Usage
-----
    import dielfigs
    D = dielfigs.load_all(host)          # resolves inputs from the artifact store by name
    fig = dielfigs.fig02_species_curves(D)
    dielfigs.render_all(host, outdir="figs")

Conventions that are load-bearing
---------------------------------
SUN-ANCHORED TIME runs 0 = sunrise, 12 = sunset, 24 = next sunrise. Night is 12 to 24. Drawing it
as midnight-to-midnight puts nocturnal species in daylight; verify_curve_convention() checks this
against the stored measures and is called by every curve figure.

PEAK TIME (peak_h) is CIRCULAR. Never draw it on a linear sequential ramp; use CYCLIC_CMAP.

GUILD COLOURS are by behaviour, never by which analysis wave introduced a species.
"""
