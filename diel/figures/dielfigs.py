def fig01_data_coverage(D, style=None):
    """Where and when the data come from: site map, per-species counts, seasonal coverage."""
    if style:
        style()
    arrays, harm, spf, sources = D["arrays"], D["harmonics"], D["species"], D["sources"]
    used = set(harm.final_array.astype(str))
    sites = (arrays[arrays.final_array.astype(str).isin(used)]
             .groupby("final_array")
             .agg(lat=("latitude", "mean"), lon=("longitude", "mean"), ncam=("dep_key", "nunique"))
             .reset_index())
    sx, sy = albers(sites.lon.values, sites.lat.values)
    det_col = [c for c in spf.columns if "det" in c.lower()][0]
    d = spf.sort_values(det_col)
    nsit = harm.groupby("species").final_array.nunique().reindex(d.index)

    fig = plt.figure(figsize=(11.0, 8.6))
    gs = fig.add_gridspec(2, 3, height_ratios=[1.55, 1], hspace=.26, wspace=.36)
    ax = fig.add_subplot(gs[0, :])
    ax.set_facecolor("#fbfbfa")
    draw_states(ax, D["states"])
    o = np.argsort(sites.ncam.values)
    sc = ax.scatter(sx[o], sy[o], s=5 + sites.ncam.values[o] * .75, c=sites.ncam.values[o],
                    cmap=SEQ_CMAP, lw=.25, edgecolor="white", alpha=.9, zorder=3)
    ax.set_xlim(-.385, .375); ax.set_ylim(-.225, .262)
    ax.set_aspect("equal"); ax.axis("off")
    cb = fig.colorbar(sc, ax=ax, fraction=.024, pad=.005, shrink=.82)
    cb.set_label("cameras at the site", fontsize=6.8); cb.ax.tick_params(labelsize=6)
    ndep = int(sources.deployments.sum())
    ax.set_title(f"a   {len(sites)} sites, {ndep:,} cameras that detected a study species, "
                 f"{len(sources)} projects", loc="left", fontsize=9)

    for i, (cell, ttl, col, vals, xlab) in enumerate([
            (gs[1, 0], "b   Detections per species", "#1f6f8b", d[det_col].values / 1000,
             "independent detections (thousands)"),
            (gs[1, 1], "c   Sites per species", "#2e7d4f", nsit.values,
             "sites with a fitted curve")]):
        a2 = fig.add_subplot(cell)
        a2.barh(range(len(vals)), vals, color=col, height=.74)
        a2.set_yticks(range(len(vals)))
        a2.set_yticklabels(d.index if i == 0 else [], fontsize=6.2)
        a2.set_xlabel(xlab); a2.set_title(ttl, loc="left", fontsize=9)

    ax = fig.add_subplot(gs[1, 2])
    dd = D.get("dep_dates")
    if dd is not None:
        keys = arrays[arrays.final_array.astype(str).isin(used)].dep_key.astype(str)
        sub = dd.reindex(keys).dropna()
        sd = pd.to_datetime(sub.start_date, errors="coerce")
        ed = pd.to_datetime(sub.end_date, errors="coerce")
        ok = sd.notna() & ed.notna()
        sd, ed = sd[ok], ed[ok]
    else:
        sd = None
    if sd is not None and len(sd):
        weeks = pd.date_range("2000-08-01", "2000-10-31", freq="W")
        cnt = [int(((sd.dt.dayofyear <= w.dayofyear) & (ed.dt.dayofyear >= w.dayofyear)).sum())
               for w in weeks]
        ax.fill_between(range(len(weeks)), cnt, color="#1f6f8b", alpha=.30)
        ax.plot(range(len(weeks)), cnt, color="#1f6f8b", lw=1.5)
        ax.set_xticks([0, 4, 8, 12])
        ax.set_xticklabels(["1 Aug", "1 Sep", "1 Oct", "31 Oct"], fontsize=6.4)
        ax.set_ylabel("cameras active"); ax.set_ylim(0, max(cnt) * 1.12)
    else:
        ax.axis("off")
        ax.text(.5, .5, "deployment export not available", ha="center", va="center",
                fontsize=7, color=MUTED, transform=ax.transAxes)
    ax.set_title("d   Coverage through the window", loc="left", fontsize=9)
    fig.suptitle("Where the data come from", fontsize=10.5, y=.955)
    return fig


def fig02_species_curves(D, style=None, n_show=200, seed=0):
    """The daily activity schedule of each species, sites behind the species average.

    Species are coloured by behavioural guild, never by analysis provenance.
    """
    if style:
        style()
    harm = D["harmonics"]
    verify_curve_convention(harm)
    t, _ = curve_grid()
    order = harm.groupby("species").pct_noct.mean().sort_values().index.tolist()
    rng = np.random.default_rng(seed)

    fig, axs = plt.subplots(4, 4, figsize=(13.6, 11.6), gridspec_kw=dict(hspace=.72, wspace=.30))
    for k, sp in enumerate(order):
        ax = axs.ravel()[k]
        g = harm[harm.species == sp].dropna(subset=["s1", "c1", "s2", "c2"])
        M = curves_from_harmonics(g, t)
        night_pct = float(g.pct_noct.mean())
        col = GUILD_COLOUR[guild(night_pct)]
        ax.axvspan(12, 24, color=NIGHT_SHADE, zorder=0, lw=0)
        sel = rng.choice(len(M), min(len(M), n_show), replace=False)
        for row in M[sel]:
            ax.plot(t, row * 1000, color=col, lw=.35, alpha=.15, zorder=2)
        mu = M.mean(axis=0) * 1000
        ax.plot(t, mu, color=col, lw=2.3, zorder=4, solid_capstyle="round")
        ax.set_title(f"{sp}\n{night_pct:.0f}% of activity at night  \u00b7  {len(g)} sites",
                     loc="left", fontsize=7.3, pad=4, color=col)
        ax.set_xlim(0, 24); ax.set_xticks([0, 6, 12, 18, 24])
        ax.set_xticklabels(["sunrise", "noon", "sunset", "midnight", "sunrise"], fontsize=5.8)
        ax.set_ylim(0, max(mu.max() * 2.3, 1)); ax.tick_params(axis="y", labelsize=5.8)
        if k % 4 == 0:
            ax.set_ylabel("share of daily activity\n(per mille per half hour)", fontsize=6.1)
    for k in range(len(order), 16):
        axs.ravel()[k].axis("off")
    lo, hi = GUILD_BOUNDS
    lab = {"diurnal": f"diurnal (under {lo:.0f}% at night)",
           "intermediate": f"intermediate ({lo:.0f} to {hi:.0f}%)",
           "nocturnal": f"nocturnal (over {hi:.0f}%)"}
    axs.ravel()[15].legend(
        handles=[Line2D([], [], color=GUILD_COLOUR[g_], lw=2.3, label=lab[g_])
                 for g_ in ["diurnal", "intermediate", "nocturnal"]]
        + [Line2D([], [], color=MUTED, lw=1.0, alpha=.6, label="one site"),
           Patch(facecolor=NIGHT_SHADE, edgecolor="none", label="hours of darkness")],
        fontsize=7.2, frameon=False, loc="center left")
    fig.suptitle("The daily activity schedule of each species, and how much sites differ within it",
                 fontsize=11, y=.995)
    return fig


