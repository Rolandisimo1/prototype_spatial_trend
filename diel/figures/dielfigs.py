def _resolve(host, filename):
    a = host.artifacts(filename=filename, exact=True, limit=6)
    if not a["artifacts"]:
        raise FileNotFoundError(f"no artifact named {filename!r}")
    best = sorted(a["artifacts"], key=lambda x: x["size_bytes"], reverse=True)[0]
    return host.artifact_path(best["latest_version_id"])


def load_all(host, extra=None, deployments_csv=DEPLOYMENTS_CSV):
    """Resolve and load every input. Returns a dict keyed as in INPUTS.

    `deployments_csv` supplies deployment start and end dates for the coverage panel. If the file
    is absent the panel is skipped and the rest of the figure still renders.
    """
    import os
    spec = dict(INPUTS)
    if extra:
        spec.update(extra)
    out = {}
    for key, fn in spec.items():
        path = _resolve(host, fn)
        if fn.endswith(".json"):
            with open(path) as fh:
                out[key] = json.load(fh)
        else:
            idx = 0 if key in ("species", "corr") else None
            out[key] = pd.read_csv(path, index_col=idx, low_memory=False)
    if deployments_csv and os.path.exists(deployments_csv):
        dep = pd.read_csv(deployments_csv, low_memory=False,
                          usecols=["project_id", "deployment_id", "start_date", "end_date"])
        dep["dep_key"] = dep.project_id.astype(str) + "|" + dep.deployment_id.astype(str)
        out["dep_dates"] = dep.drop_duplicates("dep_key").set_index("dep_key")[
            ["start_date", "end_date"]]
    else:
        out["dep_dates"] = None
    return out


# ---------------------------------------------------------------- curve helpers

def curve_grid(n=289):
    """Sun-anchored time grid in hours, 0 = sunrise, 12 = sunset."""
    t = np.linspace(0, 24, n)
    return t, 2 * np.pi * t / 24


def curves_from_harmonics(g, t=None):
    """Fitted activity curves from stored harmonic coefficients, rows normalised to sum to 1."""
    if t is None:
        t, _ = curve_grid()
    th = 2 * np.pi * t / 24
    M = np.exp(
        np.outer(g["s1"].values, np.sin(th)) + np.outer(g["c1"].values, np.cos(th))
        + np.outer(g["s2"].values, np.sin(2 * th)) + np.outer(g["c2"].values, np.cos(2 * th))
    )
    return M / M.sum(axis=1, keepdims=True)


def verify_curve_convention(harmonics, tol=1.0):
    """Night share recomputed from the curves must match the stored pct_noct.

    This exists because drawing sun-anchored time as midnight-to-midnight silently puts
    nocturnal species in daylight. Raises if the convention is wrong.
    """
    t, _ = curve_grid()
    night = (t >= 12) & (t < 24)
    rows = []
    for sp, g in harmonics.dropna(subset=["s1", "c1", "s2", "c2"]).groupby("species"):
        M = curves_from_harmonics(g, t)
        drawn = float((M[:, night].sum(axis=1) * 100).mean())
        rows.append((sp, drawn, float(g["pct_noct"].mean())))
    chk = pd.DataFrame(rows, columns=["species", "drawn", "stored"])
    chk["delta"] = (chk.drawn - chk.stored).abs()
    if chk.delta.max() > tol:
        worst = chk.loc[chk.delta.idxmax()]
        raise AssertionError(
            f"sun-time convention wrong: {worst.species} drawn {worst.drawn:.1f} "
            f"vs stored {worst.stored:.1f}. Night is sun-time 12 to 24, not 0-6 and 18-24."
        )
    return chk


def guild(pct_night):
    lo, hi = GUILD_BOUNDS
    return "diurnal" if pct_night < lo else ("nocturnal" if pct_night > hi else "intermediate")


def draw_states(ax, states_json, lw=0.45, color="#b9bfc4", zorder=1):
    """Lower-48 outlines in Albers space. Requires mapproj on the path."""
    import mapproj
    return mapproj.draw_states(ax, states_json, lw=lw, color=color, zorder=zorder)


def albers(lon, lat):
    import mapproj
    return mapproj.albers(lon, lat)


def _overlaps(fig):
    """Count text-text overlaps. Advisory: leader lines and math text give false positives."""
    r = fig.canvas.get_renderer()
    tt = [(x, x.get_window_extent(r)) for x in fig.findobj(mpl.text.Text)
          if x.get_text().strip() and x.get_visible()]
    return sum(1 for i, (_, ba) in enumerate(tt) for _, bb in tt[i + 1:] if ba.overlaps(bb))


