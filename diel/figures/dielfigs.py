    if len(act):
        ya = len(piv.index) + .55
        ax.axhline(len(piv.index) - .1, color="#d5d9dc", lw=.8)
        for j, mm in enumerate(cols):
            pass
        ax.scatter([len(cols) / 2 - .5], [ya], s=42 + 150 * float(act.reliability.median()),
                   c="#ffffff", edgecolor="#b5442e", lw=1.4, zorder=3)
